import { buildParserFile } from "@lezer/generator";
import * as esbuild from "esbuild";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pkgRoot = path.resolve(__dirname, "..");
const srcDir = path.join(pkgRoot, "src");
const distDir = path.join(pkgRoot, "dist");

const generateOnly = process.argv.includes("--generate-only");

function generateParser() {
  const grammarPath = path.join(srcDir, "cacl.grammar");
  const grammar = fs.readFileSync(grammarPath, "utf8");
  const { parser, terms } = buildParserFile(grammar, {
    fileName: "cacl.grammar",
    typeScript: true,
    moduleStyle: "es",
  });

  const banner = "// This file is auto-generated by @lezer/generator from src/cacl.grammar.\n";
  // Disable strict checks inside generated parser tables while keeping public types intact.
  fs.writeFileSync(path.join(srcDir, "parser.ts"), `${banner}// @ts-nocheck\n${parser}`, "utf8");
  fs.writeFileSync(path.join(srcDir, "parser.terms.ts"), `${banner}${terms}`, "utf8");
}

async function bundle() {
  fs.mkdirSync(distDir, { recursive: true });
  const shared = {
    entryPoints: [path.join(srcDir, "index.ts")],
    bundle: true,
    platform: "neutral",
    target: "es2022",
    sourcemap: true,
    external: ["@codemirror/*", "@lezer/*"],
    logLevel: "info",
  };

  await Promise.all([
    esbuild.build({
      ...shared,
      format: "esm",
      outfile: path.join(distDir, "index.js"),
    }),
    esbuild.build({
      ...shared,
      format: "cjs",
      outfile: path.join(distDir, "index.cjs"),
    }),
  ]);
}

generateParser();
if (!generateOnly) {
  await bundle();
}
